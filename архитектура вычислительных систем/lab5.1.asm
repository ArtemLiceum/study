WR R3
OR #0
CIKLE_START:; сложение в цикле 
RD @R1+ ; считали число 
ADC @R2+ ; добавили второе число, флаг переноса запомнился
DAA ; корректировка
WR @R3+
DJRNZ R0,CIKLE_START
JNC K ;если не перенос
RD #1 ;если перенос добавим единицу в старший разряд
WR @R3+
RD R4
WR R0
K:
RD R4
CMP R6
JMP FIRST_IT ; вывод первого числа отличается поэтому идем по метке
K1: 
RD R3 ; в R3 адрес текущей ячейки 
CMP #0x70 ; проверям не вывели ли все
JZ END ; если вывели то закончим программу
RD -@R3 ; считаем число
WR R6 ; запомнили в R6
AND #0xF0 ; взяли его левую часть
SWAPA
OR #0x30
WR R7 ; запишем в R7 
CALL MYOUT
RD R6 
AND #0x0F ; взяли его левую часть
OR #0x30
WR R7
CALL MYOUT
RD R3
CMP #0x70 ; проверим снова не закончили ли мы выводить число
JZ END ; если закончили то завершаем программу
JMP K1 ; продолжим выводить
END:
HLT
FIRST_IT: ; левая часть это большое число
RD #0x74;проверка нужна ли будет точка для метки что число длинное
CMP R3
JNN NEED_DOT;
JN NOT_NEED_DOT
NEED_DOT:; если нужна будет точка ставим флаг в 0х30
