M:
SBIS 2,1        ; Проверяем бит 1 регистра 2
JMP M           ; Если бит не установлен, остаёмся в цикле
IN 0            ; Читаем данные с входа
CMP #0x2B       ; Сравниваем с '+'
JZ PACK        
CMP #0x3D       ; Сравниваем с '='
JZ PACK         
CMP #0x39       ; Проверяем, больше ли 9
JC M            
CMP #0x2F       ; Проверяем, меньше ли 0
JNC M           
WR @R0+           
JMP M           
; Упаковка числа
PACK:
RD -@R0         ; Читаем предыдущий символ
WR R5           ; Сохраняем в R5
AND #0x0F       ; Выделяем младший разряд
WR R2           ; Сохраняем в R2
CALL CHECK      ; Проверяем значение
RD -@R0         ; Читаем следующий символ
WR R5           ; Сохраняем в R5
AND #0x0F       ; Выделяем младший разряд
SWAPA           ; Меняем местами старшие и младшие разряды
OR R2           ; Объединяем младший и старший разряды
WR @R3+         ; Сохраняем результат в память, указатель R3 увеличивается
RD R4           ; Читаем счётчик байтов
INCA            ; Увеличиваем его на 1
WR R4           ; Сохраняем обратно
CALL CHECK      ; Проверяем значение
JMP PACK     ; Продолжаем упаковку
; Проверка значения
CHECK:
RD R5           
OR R5           
JZ WRITER       
RET             
; Запись числа
WRITER:
RD #0x10        ; Устанавливаем начальный адрес первого числа
WR R0
RD #0x60        ; Устанавливаем начальный адрес результата
WR R3
IN 0            ; Читаем символ
CMP #0x3D       ; Проверяем, является ли он '='
JZ MAX          ; Если да, переходим к MAX
RD R4           ; Читаем счётчик
WR R6           ; Сохраняем его в R6
RD #0           ; Обнуляем счётчик
WR R4
JMP M           ; Возвращаемся к ожиданию
; Максимизация результата
MAX:
RD R4           ; Читаем текущий счётчик
CMP R6          ; Сравниваем с R6
JNC MAX_1       ; Если больше или равно, идём дальше
MAX_CON:
RD R4
WR R0
RD #0x50
WR R1
RD #0x60
WR R2
